// The honest summary under a result: what was read, what was not, and the advice line. Used by the card and the popup.
globalThis.HALT_SCAN_NOTES = (S, r) =>
	[
		S.stats(r.read, r.candidates, r.totalEntries),
		r.tooLargeCount > 0 && S.tooLarge(r.tooLargeCount, r.tooLarge.join(", ") + (r.tooLargeCount > r.tooLarge.length ? ", …" : "")),
		r.unreadable > 0 && S.unreadable(r.unreadable),
		r.stopped && S.stopped(r.unread),
		S.note,
	].filter(Boolean);
